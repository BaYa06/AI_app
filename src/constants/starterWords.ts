/**
 * Слова стартового набора (plan/new/new_user_activation.md, Start 1.1).
 *
 * Храним понятия, а не пары языков: у каждого понятия есть слово и пример на всех 10 языках
 * TOP_LANGUAGES, любая пара «изучаемый → родной» собирается на лету (StarterSetService).
 *
 * - `example` — предложение на этом же языке; в нём должно встречаться слово (или `form`),
 *   иначе упражнение «Слово в контексте» не найдёт, что заменить пропуском.
 * - `form` — форма слова в примере, если она отличается от словарной (`Card.wordForm`):
 *   «먹다» → «먹어요», «Eins» → «eine».
 * - `reading` — чтение для китайского, японского и корейского. Карточка показывает его рядом
 *   с переводом: без него новичок не прочитает слово.
 *
 * Черновик переводов. До релиза каждый язык проверить носителем или по словарю: ошибка
 * в первом же наборе подрывает доверие ко всему приложению.
 */

export const STARTER_LANGS = ['en', 'de', 'ru', 'es', 'fr', 'it', 'zh', 'ja', 'ko', 'tr'] as const;
export type StarterLang = (typeof STARTER_LANGS)[number];

export interface StarterEntry {
  word: string;
  example: string;
  reading?: string;
  form?: string;
}

export interface StarterConcept {
  id: string;
  words: Record<StarterLang, StarterEntry>;
}

export type StarterThemeId = 'first_words' | 'travel';

export interface StarterTheme {
  id: StarterThemeId;
  title: string;
  concepts: StarterConcept[];
}

type Row = [word: string, example: string, extra?: { reading?: string; form?: string }];

function concept(id: string, rows: Record<StarterLang, Row>): StarterConcept {
  const words = {} as Record<StarterLang, StarterEntry>;
  for (const lang of STARTER_LANGS) {
    const [word, example, extra] = rows[lang];
    words[lang] = { word, example, ...extra };
  }
  return { id, words };
}

