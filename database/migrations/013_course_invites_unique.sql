-- Миграция 013: UNIQUE(course_id) на course_invites
--
-- Раньше "проверить есть ли инвайт → если нет, создать" делалось двумя отдельными
-- запросами без блокировки — двойной тап по "Пригласить" (или повторный вызов эффекта)
-- мог создать два разных token/join_code для одного и того же курса. Второй, "потерянный"
-- инвайт при этом оставался рабочим и неотзываемым способом входа в курс.
--
-- Ограничение ниже делает создание/переиспользование инвайта одной атомарной операцией
-- через INSERT ... ON CONFLICT (course_id) DO UPDATE — см. api/teacher.js, action=create-invite.
--
-- На момент написания миграции дубликатов course_id в course_invites не было
-- (проверено запросом к проду), поэтому ALTER TABLE ниже безопасен без отдельного шага
-- дедупликации. Если у вас есть дубликаты — сначала удалите лишние строки вручную.

ALTER TABLE course_invites
  ADD CONSTRAINT course_invites_course_id_unique UNIQUE (course_id);
